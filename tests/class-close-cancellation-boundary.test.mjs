import assert from "node:assert/strict";
import test from "node:test";
import { createClient } from "@supabase/supabase-js";
import { createManagementService } from "../src/features/management/management-service.js";
import { timetableOperationalErrorMessage } from "../src/features/academic/timetable-operational-service.ts";

const classId = "10000000-0000-4000-8000-000000000234";
const requestKey = "20000000-0000-4000-8000-000000000234";
const input = {
  id: classId, name: "취소 경계 합성 수업", classType: "정규", subject: "수학", grade: "고1",
  teacher: "합성 교사", schedule: "화 17:00-19:00", classroom: "합성 강의실", capacity: 12,
  fee: 100, status: "종강", textbook_ids: [], public_memo: "합성 공개 안내",
};
const emptyPage = () => ({ rows: [], hasMore: false, nextCursor: null });
const detail = status => ({
  kind: "classes", record: {
    id: classId, name: input.name, classType: "정규", subject: "수학", subjectAreaKey: null,
    grade: "고1", teacher: input.teacher, schedule: input.schedule, classroom: input.classroom,
    capacity: 12, fee: 100, status, textbookIds: [], publicMemo: input.public_memo,
  },
  registeredCount: 0, waitlistCount: 0,
  registeredStudents: emptyPage(), waitlistedStudents: emptyPage(),
});
const jsonResponse = (body, status = 200) => new Response(JSON.stringify(body), {
  status, headers: { "content-type": "application/json" },
});

function serviceFor(fetch, refresh) {
  const client = createClient("https://synthetic.invalid", "synthetic-anon-key", {
    auth: { persistSession: false, autoRefreshToken: false }, global: { fetch },
  });
  return createManagementService({
    supabase: client, generateId: () => requestKey,
    probeRegistrationRuntime: async () => ({ mode: "ready" }),
    refreshPublicClassesCache: refresh,
  });
}

test("an HTTP 57014 response from the installed transport remains an explicit rejection without readback", async () => {
  for (const message of ["canceling statement due to statement timeout", "canceling statement due to user request"]) {
    const requests = [];
    let checking = 0;
    const service = serviceFor(async (url, options) => {
      requests.push({ path: new URL(url).pathname, body: JSON.parse(options.body) });
      return jsonResponse({ code: "57014", message, details: null, hint: null }, 500);
    }, async () => assert.fail("rejected close must not refresh public data"));
    const draft = structuredClone(input);
    await assert.rejects(service.updateClass(draft, {
      confirmCloseResult: { isCurrent: () => true, onChecking: () => checking++ },
    }), error => {
      assert.equal(error.code, "57014");
      assert.equal(error.message, message);
      assert.equal(timetableOperationalErrorMessage(error, "fallback"),
        "일정 확인에 시간이 오래 걸려 저장이 중단되었습니다. 잠시 후 다시 저장해 주세요.");
      return true;
    });
    assert.equal(checking, 0);
    assert.deepEqual(requests.map(request => request.path), ["/rest/v1/rpc/update_class_operational_v1"]);
    assert.equal(requests[0].body.p_patch.status, "종강");
    assert.equal(requests[0].body.p_request_key, requestKey);
    assert.deepEqual(draft, input);
  }
});

test("a client deadline hides any later server response and checks current state without resubmitting the writer", async () => {
  // Controlled deadlines exercise the real SDK abort contract without an 8s
  // wall-clock sleep. This does not model server cancellation/commit latency.
  for (const committedBeforeRead of [false, true]) {
    const originalTimeout = AbortSignal.timeout;
    const deadlines = [];
    const writerController = new AbortController();
    const started = Promise.withResolvers();
    const requests = [];
    let state = committedBeforeRead ? "종강" : "수강";
    let checks = 0;
    let refreshes = 0;
    let resolveLateResponse;
    AbortSignal.timeout = milliseconds => {
      deadlines.push(milliseconds);
      return deadlines.length === 1 ? writerController.signal : new AbortController().signal;
    };
    try {
      const service = serviceFor(async (url, options) => {
        const path = new URL(url).pathname;
        requests.push(path);
        if (path === "/rest/v1/rpc/update_class_operational_v1") {
          const payload = JSON.parse(options.body);
          assert.equal(payload.p_patch.status, "종강");
          assert.equal(payload.p_request_key, requestKey);
          assert.equal(payload.p_expected_schedule_plan, null);
          // The close timestamp is generated by the server's atomic close;
          // neither a client timestamp nor roster arrays are patch inputs.
          for (const key of ["closed_at", "student_ids", "waitlist_ids", "id"]) {
            assert.equal(Object.hasOwn(payload.p_patch, key), false);
          }
          started.resolve();
          return new Promise((resolve, reject) => {
            resolveLateResponse = resolve;
            options.signal.addEventListener("abort", () => reject(options.signal.reason), { once: true });
          });
        }
        assert.equal(path, "/rest/v1/rpc/get_management_detail_v1");
        assert.deepEqual(JSON.parse(options.body), { p_kind: "classes", p_id: classId });
        return jsonResponse(detail(state));
      }, async () => { refreshes++; return { status: "complete" }; });
      const draft = structuredClone(input);
      const outcome = service.updateClass(draft, {
        confirmCloseResult: { isCurrent: () => true, onChecking: () => checks++ },
      }).then(value => ({ value }), error => ({ error }));
      await started.promise;
      writerController.abort(new DOMException("synthetic response deadline", "TimeoutError"));
      const result = await outcome;
      if (committedBeforeRead) {
        assert.equal(result.value.closeConfirmation, "current-state");
        assert.equal(Object.hasOwn(result.value, "closeResult"), false);
        assert.equal(refreshes, 1);
      } else {
        assert.equal(result.error.code, "CLASS_CLOSE_RESULT_UNCERTAIN");
        assert.equal(result.error.message, "종강 반영 여부를 확인하지 못했습니다. 입력은 유지됩니다.");
        assert.equal(refreshes, 0);
        // A late server cancellation cannot overwrite the failed fetch. A
        // second click uses confirm(), which still observes the active class.
        resolveLateResponse(jsonResponse({ code: "57014", message: "canceling statement due to user request" }, 500));
        await assert.rejects(result.error.confirm(), { code: "CLASS_CLOSE_RESULT_UNCERTAIN" });
        assert.equal(refreshes, 0);
        // A later matching state can be acknowledged, without claiming this
        // request committed and without a new mutation.
        state = "종강";
        assert.equal((await result.error.confirm()).closeConfirmation, "current-state");
        assert.equal(refreshes, 1);
      }
      assert.equal(requests.filter(path => path.endsWith("update_class_operational_v1")).length, 1);
      assert.equal(requests.filter(path => path.endsWith("get_management_detail_v1")).length, committedBeforeRead ? 1 : 3);
      assert.equal(checks, committedBeforeRead ? 1 : 3);
      assert.deepEqual(deadlines, committedBeforeRead ? [8000, 8000, 3000] : [8000, 8000, 8000, 8000, 3000]);
      assert.deepEqual(draft, input);
    } finally {
      AbortSignal.timeout = originalTimeout;
    }
  }
});
