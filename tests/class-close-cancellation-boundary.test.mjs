test("an HTTP 57014 response from the installed transport remains an explicit rejection without readback", async () => {
  for (const message of ["canceling statement due to statement timeout", "canceling statement due to user request"]) {
    const requests = [];
    let checking = 0;
    const service = serviceFor(async (url, options) => {
      requests.push({ path: new URL(url).pathname, body: JSON.parse(options.body) });
      return jsonResponse({ code: "57014", message, details: null, hint: null }, 500);
    }, async () => assert.fail("rejected close must not refresh public data"));
    const draft = structuredClone(input);
    await assert.rejects(service.updateClass(draft, {
      confirmCloseResult: { isCurrent: () => true, onChecking: () => checking++ },
    }), error => {
      assert.equal(error.code, "57014");
      assert.equal(error.message, message);
      assert.equal(timetableOperationalErrorMessage(error, "fallback"),
        "일정 확인에 시간이 오래 걸려 저장이 중단되었습니다. 잠시 후 다시 저장해 주세요.");
      return true;
    });
    assert.equal(checking, 0);
    assert.deepEqual(requests.map(request => request.path), ["/rest/v1/rpc/update_class_operational_v1"]);
    assert.equal(requests[0].body.p_patch.status, "종강");
    assert.equal(requests[0].body.p_request_key, requestKey);
    assert.deepEqual(draft, input);
  }
});

test("a client deadline hides any later server response and checks current state without resubmitting the writer", async () => {
  // Controlled deadlines exercise the real SDK abort contract without an 8s
  // wall-clock sleep. This does not model server cancellation/commit latency.
  for (const committedBeforeRead of [false, true]) {
    const originalTimeout = AbortSignal.timeout;
    const deadlines = [];
    const writerController = new AbortController();
    const started = Promise.withResolvers();
    const requests = [];
    let state = committedBeforeRead ? "종강" : "수강";
    let checks = 0;
    let refreshes = 0;
    let resolveLateResponse;
    AbortSignal.timeout = milliseconds => {
      deadlines.push(milliseconds);
      return deadlines.length === 1 ? writerController.signal : new AbortController().signal;
    };
    try {
      const service = serviceFor(async (url, options) => {
        const path = new URL(url).pathname;
        requests.push(path);
        if (path === "/rest/v1/rpc/update_class_operational_v1") {
          const payload = JSON.parse(options.body);
          assert.equal(payload.p_patch.status, "종강");
          assert.equal(payload.p_request_key, requestKey);
          assert.equal(payload.p_expected_schedule_plan, null);
          // The close timestamp is generated by the server's atomic close;
          // neither a client timestamp nor roster arrays are patch inputs.
          for (const key of ["closed_at", "student_ids", "waitlist_ids", "id"]) {
            assert.equal(Object.hasOwn(payload.p_patch, key), false);
          }
          started.resolve();
          return new Promise((resolve, reject) => {
            resolveLateResponse = resolve;
            options.signal.addEventListener("abort", () => reject(options.signal.reason), { once: true });
          });
        }
        assert.equal(path, "/rest/v1/rpc/get_management_detail_v1");
        assert.deepEqual(JSON.parse(options.body), { p_kind: "classes", p_id: classId });
        return jsonResponse(detail(state));
      }, async () => { refreshes++; return { status: "complete" }; });
      const draft = structuredClone(input);
      const outcome = service.updateClass(draft, {
        confirmCloseResult: { isCurrent: () => true, onChecking: () => checks++ },
      }).then(value => ({ value }), error => ({ error }));
      await started.promise;
      writerController.abort(new DOMException("synthetic response deadline", "TimeoutError"));
      const result = await outcome;
      if (committedBeforeRead) {
        assert.equal(result.value.closeConfirmation, "current-state");
        assert.equal(Object.hasOwn(result.value, "closeResult"), false);
        assert.equal(refreshes, 1);
      } else {
        assert.equal(result.error.code, "CLASS_CLOSE_RESULT_UNCERTAIN");
        assert.equal(result.error.message, "종강 반영 여부를 확인하지 못했습니다. 입력은 유지됩니다.");
        assert.equal(refreshes, 0);
        // A late server cancellation cannot overwrite the failed fetch. A
        // second click uses confirm(), which still observes the active class.
        resolveLateResponse(jsonResponse({ code: "57014", message: "canceling statement due to user request" }, 500));
        await assert.rejects(result.error.confirm(), { code: "CLASS_CLOSE_RESULT_UNCERTAIN" });
        assert.equal(refreshes, 0);
        // A later matching state can be acknowledged, without claiming this
        // request committed and without a new mutation.
        state = "종강";
        assert.equal((await result.error.confirm()).closeConfirmation, "current-state");
        assert.equal(refreshes, 1);
      }
      assert.equal(requests.filter(path => path.endsWith("update_class_operational_v1")).length, 1);
      assert.equal(requests.filter(path => path.endsWith("get_management_detail_v1")).length, committedBeforeRead ? 1 : 3);
      assert.equal(checks, committedBeforeRead ? 1 : 3);
      assert.deepEqual(deadlines, committedBeforeRead ? [8000, 8000, 3000] : [8000, 8000, 8000, 8000, 3000]);
      assert.deepEqual(draft, input);
    } finally {
      AbortSignal.timeout = originalTimeout;
    }
  }
});

// Authentication before HTTP dispatch is distinct from response cancellation.
const tick = () => new Promise(resolve => setImmediate(resolve));
const expired = () => new DOMException("Synthetic eight-second deadline", "TimeoutError");
for (const { detailConfirmation, lateAuthFailure } of [
  { detailConfirmation: false, lateAuthFailure: false },
  { detailConfirmation: true, lateAuthFailure: false },
  { detailConfirmation: false, lateAuthFailure: true },
  { detailConfirmation: true, lateAuthFailure: true },
]) {
  test(`${detailConfirmation ? "detail" : "bulk"} close bounds pre-fetch auth wait with late auth ${lateAuthFailure ? "failure" : "success"}`, async t => {
    const token = Promise.withResolvers();
    const authStarted = Promise.withResolvers();
    const deadlines = [];
    const attempts = [];
    let externalRequests = 0, transportWork = 0, checking = 0, settled = false;
    t.mock.method(globalThis, "fetch", async () => {
      externalRequests++;
      assert.fail("external requests are forbidden in this synthetic fixture");
    });
    t.mock.method(AbortSignal, "timeout", ms => {
      assert.equal(ms, 8000);
      const controller = new AbortController();
      deadlines.push(controller);
      return controller.signal;
    });
    const client = createClient("https://synthetic.invalid", "fixture-only", {
      auth: { persistSession: false, autoRefreshToken: false },
      global: { fetch: async (url, init) => {
        const path = new URL(url).pathname;
        attempts.push({ path, aborted: init.signal.aborted });
        // Native fetch rejects an already-aborted request before HTTP dispatch.
        init.signal.throwIfAborted();
        transportWork++;
        assert.equal(path, "/rest/v1/rpc/get_management_detail_v1");
        return jsonResponse({ kind: "classes", record: { id: classId, status: "수강" } });
      } },
    });
    t.mock.method(client.auth, "getSession", () => {
      authStarted.resolve();
      return token.promise;
    });
    const service = createManagementService({ supabase: client, generateId: () => requestKey,
      probeRegistrationRuntime: async () => ({ mode: "ready" }),
      refreshPublicClassesCache: async () => assert.fail("unconfirmed close must not refresh") });
    const draft = structuredClone(input);
    const pending = service.updateClass(draft, detailConfirmation ? {
      confirmCloseResult: { isCurrent: () => true, onChecking: () => checking++ },
    } : {}).then(value => { settled = true; return { value }; }, error => { settled = true; return { error }; });
    await authStarted.promise;
    assert.equal(attempts.length, 0);
    deadlines[0].abort(expired());
    await tick();
    const afterWriteDeadline = { settled, checking, deadlineCount: deadlines.length };
    // Detail confirmation is a separate bounded read, not an extra writer.
    if (detailConfirmation && deadlines[1]) {
      deadlines[1].abort(expired());
      await tick();
    }
    const settledBeforeAuth = settled;
    // Drain the original SDK operation, including on the failing baseline.
    if (lateAuthFailure) token.reject(new Error("Synthetic late authentication failure"));
    else token.resolve({ data: { session: { access_token: "synthetic-token" } }, error: null });
    const result = await pending;
    await tick(); await tick();
    t.diagnostic(JSON.stringify({ afterWriteDeadline, settledBeforeAuth, attempts, transportWork, externalRequests }));
    assert.equal(externalRequests, 0);
    assert.equal(attempts.filter(x => x.path.endsWith("update_class_operational_v1")).length, lateAuthFailure ? 0 : 1);
    assert.ok(attempts.every(x => x.aborted));
    assert.deepEqual(draft, input);
    assert.deepEqual(afterWriteDeadline, detailConfirmation
      ? { settled: false, checking: 1, deadlineCount: 2 }
      : { settled: true, checking: 0, deadlineCount: 1 });
    assert.equal(settledBeforeAuth, true, "auth must not extend the writer or confirmation deadline");
    assert.equal(transportWork, 0, "late token completion must not dispatch an expired write or read");
    if (detailConfirmation) assert.equal(result.error.code, "CLASS_CLOSE_RESULT_UNCERTAIN");
    else {
      assert.equal(result.error.name, "TimeoutError");
      assert.equal(result.error.code, undefined, "a browser deadline must not look like a SQLSTATE rejection");
    }
  });
}

test("a close deadline expired before startup never calls the RPC factory", async () => {
  const controller = new AbortController();
  controller.abort(expired());
  await assert.rejects(withClassCloseWriteDeadline(() => assert.fail("expired writer started"), controller.signal), error => {
    assert.equal(error.name, "TimeoutError");
    assert.equal(error.code, undefined);
    return true;
  });
});

test("close deadline preserves explicit errors and a receipt already delivered before expiry", async () => {
  const controller = new AbortController();
  const failure = { code: "57014", message: "Synthetic explicit server rejection" };
  await assert.rejects(withClassCloseWriteDeadline(() => { throw failure; }, controller.signal), error => error === failure);
  const receipt = { closeResult: { id: classId, classId, status: "종강" } };
  assert.equal(await withClassCloseWriteDeadline(() => Promise.resolve(receipt), controller.signal), receipt);
  controller.abort(expired());
  await tick();
});
